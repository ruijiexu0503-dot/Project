def _enabled_for_doc(doc_id, config, key):
    cfg = config.get(key, {})
    if not cfg.get("enabled", False):
        return False
    prefixes = cfg.get("document_prefixes", [])
    return not prefixes or any(doc_id.startswith(prefix) for prefix in prefixes)


def build_nodes(doc_id, config):
    pages = load_aligned_document(config["input"]["aligned_root"], doc_id)
    raw_blocks, reading_issues = order_blocks(
        pages, config["validation"]["deepseek_order_conflict_threshold"]
    )

    # Phase 0: coarse structural classification from fused DeepSeek+layout metadata.
    base_classified = [(block, classify_block_role(block)) for block in raw_blocks]

    # Magazine canonicalization is deliberately staged and audit-first:
    # repeated document chrome -> conservative page role -> block routing.
    role_routing_enabled = _enabled_for_doc(doc_id, config, "magazine_role_routing")
    template_enabled = _enabled_for_doc(doc_id, config, "repeated_template_detection")
    template_keys = set()
    template_review = []
    template_stats = {}
    page_role_report = {}
    page_role_counts = {}
    role_routing_review = []
    role_routing_counts = {}

    # Optional conservative production interface. The file is generated by an
    # upstream shadow audit and contains only approved (SAFE_TEMPLATE + mapped)
    # page/block keys. Suspicious and unresolved rows are intentionally absent.
    external_template_metadata = {}
    template_interface_cfg = config.get("template_keys", {}) or {}
    if template_interface_cfg.get("enabled", False):
        prefixes = template_interface_cfg.get("document_prefixes", [])
        if not prefixes or any(doc_id.startswith(prefix) for prefix in prefixes):
            configured_path = str(template_interface_cfg.get("path", "")).replace("{doc_id}", doc_id)
            if configured_path:
                key_path = Path(configured_path)
                if not key_path.is_absolute():
                    key_path = Path(config["output"]["graph_root"]).parent / key_path
                if key_path.exists():
                    for row in read_jsonl(key_path):
                        key = (str(row.get("page") or row.get("page_id") or ""), str(row.get("block_id") or ""))
                        if key[0] and key[1]:
                            external_template_metadata[key] = row
                    template_keys.update(external_template_metadata)
                    for block in raw_blocks:
                        metadata_row = external_template_metadata.get(block_key(block))
                        if metadata_row is not None:
                            block["_template_key_metadata"] = metadata_row
                    template_stats["external_template_keys_path"] = str(key_path)
                    template_stats["external_template_keys_loaded"] = len(external_template_metadata)

    if role_routing_enabled:
        if template_enabled:
            template_keys, template_review, template_stats = detect_repeated_templates(
                raw_blocks, config.get("repeated_template_detection", {})
            )
        page_role_report, page_role_counts = classify_magazine_pages(raw_blocks, template_keys)
        classified, role_routing_review, role_routing_counts = route_magazine_roles(
            raw_blocks,
            base_classified,
            page_roles=page_role_report,
            template_keys=template_keys,
        )
    else:
        classified = base_classified

    # Shadow policy: advertisement detection remains metadata only. When
    # explicitly enabled, advertisement blocks re-enter the ordinary evidence
    # stream without changing their original routed role in metadata. An
    # isolated audit may likewise retain template-like blocks unless their keys
    # came from the approved SAFE_TEMPLATE interface.
    advertisement_as_evidence = bool(config.get("evidence", {}).get("include_advertisement_blocks", False))
    unapproved_template_as_evidence = bool(config.get("evidence", {}).get("include_unapproved_template_blocks", False))
    classified_for_nodes = classified
    restored_advertisement_blocks = []
    restored_unapproved_template_blocks = []
    if advertisement_as_evidence or unapproved_template_as_evidence:
        classified_for_nodes = []
        for block, role in classified:
            if role == "advertisement" and advertisement_as_evidence:
                block["_original_routed_role"] = role
                classified_for_nodes.append((block, "evidence_content"))
                restored_advertisement_blocks.append(block)
            elif role == "template" and unapproved_template_as_evidence and block_key(block) not in external_template_metadata:
                block["_original_routed_role"] = role
                classified_for_nodes.append((block, "evidence_content"))
                restored_unapproved_template_blocks.append(block)
            else:
                classified_for_nodes.append((block, role))

    # Fragment diagnostics only inspect content that survives document/page/block routing.
    # Automatic fragment absorption remains blocked until this routing layer is reviewed.
    fragment_enabled = _enabled_for_doc(doc_id, config, "micro_fragment_consolidation")
    fragment_cfg = config.get("micro_fragment_consolidation", {})
    fragment_review_rows = []
    fragment_proposals = []
    fragment_stats = {}
    if fragment_enabled:
        evidence_blocks = [block for block, role in classified_for_nodes if role == "evidence_content"]
        fragment_review_rows = collect_fragment_review_rows(evidence_blocks, fragment_cfg)
        fragment_proposals, fragment_stats = propose_aligned_fragment_attachments(
            evidence_blocks, fragment_cfg
        )
        fragment_stats["routed_evidence_input_blocks"] = len(evidence_blocks)
        fragment_stats["apply"] = False
        if fragment_cfg.get("apply", False):
            fragment_stats["apply_blocked_reason"] = (
                "document-aware routing must be validated before automatic fragment absorption"
            )

    metadata = extract_document_metadata(doc_id, classified_for_nodes, [p["_source_file"] for p in pages])
    sections, assignments = build_sections(doc_id, classified_for_nodes)
    evidence = build_provisional_evidence_nodes(doc_id, classified_for_nodes, assignments)
    documents = [document_node(doc_id, metadata)]
    edges = build_structural_edges(
        doc_id,
        sections,
        evidence,
        config["structure"]["create_previous_edges"],
        config["structure"]["detect_continuations"],
    )
    validation = validate_graph(
        doc_id, pages, classified_for_nodes, documents, sections, evidence, edges, reading_issues
    )
    stats = calculate_statistics(pages, classified_for_nodes, evidence, edges)
    if advertisement_as_evidence:
        stats["advertisement_inclusion_policy"] = {
            "enabled": True,
            "advertisement_role_blocks": sum(1 for _, role in classified if role == "advertisement"),
            "advertisement_role_blocks_restored_as_nodes": len(restored_advertisement_blocks),
            "safe_template_exclusion_unchanged": True,
            "original_role_preserved_in_node_metadata": True,
        }
    if unapproved_template_as_evidence:
        stats["unapproved_template_inclusion_policy"] = {
            "enabled": True,
            "unapproved_template_blocks_restored_as_nodes": len(restored_unapproved_template_blocks),
            "approved_template_blocks_still_excluded": len(external_template_metadata),
            "original_role_preserved_in_node_metadata": True,
        }

    if role_routing_enabled:
        stats["magazine_document_canonicalization"] = {
            "repeated_templates": template_stats,
            "page_roles": page_role_counts,
            "changed_blocks": len(role_routing_review),
            "roles_after_routing": role_routing_counts,
        }
    if external_template_metadata:
        stats["template_key_interface"] = {
            "approved_template_keys": len(external_template_metadata),
            "safe_mapped_only": True,
            "suspicious_and_unresolved_included": False,
            "routed_as_template": sum(
                1 for block, role in classified
                if block_key(block) in external_template_metadata and role == "template"
            ),
            "remained_evidence_content": sum(
                1 for block, role in classified
                if block_key(block) in external_template_metadata and role == "evidence_content"
            ),
            "reconstruction_metadata_file": "template_key_review.jsonl",
        }
    if fragment_enabled:
        stats["micro_fragment_consolidation"] = {
            **fragment_stats,
            "review_rows": len(fragment_review_rows),
            "proposal_rows": len(fragment_proposals),
        }

    output = export_graph(
        config["output"]["graph_root"],
        doc_id,
        metadata,
        documents,
        sections,
        evidence,
        edges,
        validation,
        stats,
    )

    if role_routing_enabled:
        write_jsonl(output / "repeated_template_review.jsonl", template_review)
        write_json(output / "repeated_template_statistics.json", template_stats)
        write_json(output / "magazine_page_roles.json", {
            "role_counts": page_role_counts,
            "pages": page_role_report,
        })
        write_jsonl(output / "magazine_role_routing_review.jsonl", role_routing_review)
        if external_template_metadata:
            write_jsonl(output / "template_key_review.jsonl", [
                {"page": page, "block_id": block_id, **metadata}
                for (page, block_id), metadata in sorted(external_template_metadata.items())
            ])
    if advertisement_as_evidence:
        write_jsonl(output / "advertisement_restored_review.jsonl", [
            {
                "page": block.get("_page"),
                "block_id": block.get("block_id"),
                "text_preview": str(block_text(block))[:220] if "block_text" in globals() else str(block.get("text_preview") or block.get("text") or "")[:220],
                "bbox": block.get("bbox") or block.get("deepseek_bbox"),
                "original_role": "advertisement",
                "current_inclusion_decision": "included_as_evidence_content",
                "bbox_source": block.get("bbox_source"),
            }
            for block in restored_advertisement_blocks
        ])
        write_json(output / "magazine_role_routing_statistics.json", {
            "changed_blocks": len(role_routing_review),
            "roles_after_routing": role_routing_counts,
            "page_roles": page_role_counts,
            "template_blocks": template_stats.get("template_blocks", 0),
        })
    if fragment_enabled:
        write_jsonl(output / "aligned_fragment_review.jsonl", fragment_review_rows)
        write_jsonl(output / "aligned_fragment_proposals.jsonl", fragment_proposals)
        write_json(output / "aligned_fragment_statistics.json", {
            **fragment_stats,
            "review_rows": len(fragment_review_rows),
            "proposal_rows": len(fragment_proposals),
        })

    return {
        "output": str(output),
        "metadata": metadata,
        "sections": sections,
        "evidence": evidence,
        "structural_edges": edges,
        "validation": validation,
        "statistics": stats,
        "repeated_template_review": template_review,
        "magazine_page_roles": page_role_report,
        "magazine_role_routing_review": role_routing_review,
        "aligned_fragment_review": fragment_review_rows,
        "aligned_fragment_proposals": fragment_proposals,
    }
